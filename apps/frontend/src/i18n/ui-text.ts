function getLocalizedValueSet(language: AppLanguage): Set<string> {
  const existing = localizedValueSets.get(language);
  if (existing) {
    return existing;
  }

  const valueSet = new Set(Object.values(localizedTextOverrides[language] ?? {}));
  localizedValueSets.set(language, valueSet);
  return valueSet;
}

export function translateUiText(language: AppLanguage, text: string): string {
  const dictionary = localizedTextOverrides[language];
  if (!dictionary) {
    return text;
  }

  const leading = text.match(/^\s*/)?.[0] ?? "";
  const trailing = text.match(/\s*$/)?.[0] ?? "";
  const core = text.trim();
  if (!core) {
    return text;
  }

  const exact = dictionary[core];
  if (exact) {
    return `${leading}${exact}${trailing}`;
  }

  for (const entry of localizedPatternTranslations[language] ?? []) {
    const match = core.match(entry.pattern);
    if (match) {
      return `${leading}${entry.translate(...match)}${trailing}`;
    }
  }

  return text;
}

export function isKnownLocalizedUiText(language: AppLanguage, text: string): boolean {
  return getLocalizedValueSet(language).has(text.trim());
}

function shouldSkipTextElement(element: Element | null): boolean {
  return !element || Boolean(element.closest(SKIP_TEXT_SELECTOR));
}

function shouldSkipAttributeElement(element: Element | null): boolean {
  return !element || Boolean(element.closest(SKIP_ATTRIBUTE_SELECTOR));
}

function translateTextNode(node: Text, language: AppLanguage) {
  if (shouldSkipTextElement(node.parentElement)) {
    return;
  }

  const current = node.nodeValue ?? "";
  const previousTranslated = translatedTextNodes.get(node);
  const original =
    previousTranslated && current === previousTranslated
      ? (originalTextNodes.get(node) ?? current)
      : current;
  const translated = translateUiText(language, original);

  if (translated !== original) {
    originalTextNodes.set(node, original);
    translatedTextNodes.set(node, translated);
  }

  if (current !== translated) {
    node.nodeValue = translated;
  }
}

function getOriginalAttributes(element: Element): Map<string, string> {
  let originals = originalAttributes.get(element);
  if (!originals) {
    originals = new Map();
    originalAttributes.set(element, originals);
  }
  return originals;
}

function getTranslatedAttributes(element: Element): Map<string, string> {
  let translations = translatedAttributes.get(element);
  if (!translations) {
    translations = new Map();
    translatedAttributes.set(element, translations);
  }
  return translations;
}

function translateAttributes(element: Element, language: AppLanguage) {
  if (shouldSkipAttributeElement(element)) {
    return;
  }

  const originals = getOriginalAttributes(element);
  const translations = getTranslatedAttributes(element);
  for (const attribute of TRANSLATABLE_ATTRIBUTES) {
    const current = element.getAttribute(attribute);
    if (!current) {
      continue;
    }

    const previousTranslated = translations.get(attribute);
    const original =
      previousTranslated && current === previousTranslated
        ? (originals.get(attribute) ?? current)
        : current;
    const translated = translateUiText(language, original);
    if (translated !== original) {
      originals.set(attribute, original);
      translations.set(attribute, translated);
    }
    if (current !== translated) {
      element.setAttribute(attribute, translated);
    }
  }
}

function translateElement(element: Element, language: AppLanguage) {
  translateAttributes(element, language);
  element.querySelectorAll("*").forEach((child) => translateAttributes(child, language));

  const walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT);
  let node = walker.nextNode();
  while (node) {
    translateTextNode(node as Text, language);
    node = walker.nextNode();
  }
}

export function localizeDomText(root: ParentNode, language: AppLanguage) {
  if (root instanceof Element) {
    translateElement(root, language);
    return;
  }

  root.querySelectorAll?.("*").forEach((element) => translateAttributes(element, language));

  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node = walker.nextNode();
  while (node) {
    translateTextNode(node as Text, language);
    node = walker.nextNode();
  }
}
