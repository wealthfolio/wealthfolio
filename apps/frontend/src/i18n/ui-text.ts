function unitLabel(unit: string): string {
  const normalized = unit.toLowerCase();
  if (normalized === "categories") return "分类";
  if (normalized === "accounts") return "账户";
  if (normalized === "sectors") return "行业";
  if (normalized === "regions") return "地区";
  if (normalized === "levels") return "等级";
  if (normalized === "types") return "类型";
  if (normalized === "currencies") return "币种";
  if (normalized === "groups") return "分组";
  return unit;
}

function nounLabel(noun: string): string {
  const normalized = noun.toLowerCase();
  if (normalized === "classes" || normalized === "asset class" || normalized === "asset classes") {
    return "资产类别";
  }
  if (normalized === "region" || normalized === "regions") return "地区";
  if (normalized === "sector" || normalized === "sectors") return "行业";
  if (normalized === "industry" || normalized === "industries") return "行业";
  if (normalized === "account" || normalized === "accounts") return "账户";
  if (normalized === "allocation") return "配置";
  if (normalized === "security types") return "证券类型";
  if (normalized === "risk") return "风险";
  if (normalized === "currency") return "币种";
  if (normalized === "category" || normalized === "categories") return "分类";
  return noun;
}

